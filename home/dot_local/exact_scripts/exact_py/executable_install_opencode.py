#!/usr/bin/env python3
"""Install or update OpenCode from its npm platform package (@opencode/cli).

Rerun to update; --check reports without installing. On Termux this writes a
grun launcher at ~/.local/bin/opencode whose `opencode upgrade` reruns this
script.

OpenCode's CLI talks to a background server that it starts by re-executing
process.execPath. Under grun that is the glibc loader, so the server never
starts ("serve: cannot open shared object file"). The Termux launcher runs
`opencode serve` itself on loopback, with a password kept in its state dir,
and points every client command at it with --server.
"""
import os
import signal
import sys

from _npm_native import Tool, main, q, shebang

DEFAULT_PORT = 47096


def launcher(tool, lay, p):
    return f"""{shebang(p)}
# Generated by {tool.installer}; rerun it (or `opencode upgrade`) instead of editing.
# Runs OpenCode's linux-arm64 glibc build through Termux's glibc-runner and
# serves it from a loopback server started here, because OpenCode's own
# server spawn re-executes the glibc loader and fails. OPENCODE_TERMUX_PORT
# overrides the port.
bin={q(lay.binary)}
state={q(lay.state)}
port="${{OPENCODE_TERMUX_PORT:-{DEFAULT_PORT}}}"

# Commands that need no server, or that reject --server, run as given.
case "${{1-}}" in
	upgrade|update) shift; exec {q(tool.installer)} "$@" ;;
	serve|service|pair|uninstall|acp|-v|--version|-h|--help|--completions) exec grun "$bin" "$@" ;;
	debug) [ "${{2-}}" = paths ] && exec grun "$bin" "$@" ;;
esac
for arg in "$@"; do
	case "$arg" in
		--server|--server=*|--standalone) exec grun "$bin" "$@" ;;
	esac
done

up() {{ (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null; }}

mkdir -p "$state" && chmod 700 "$state" || exit 1
if [ ! -s "$state/password" ]; then
	(umask 077 && head -c 32 /dev/urandom | base64 | tr -d '/+=\\n' >"$state/password") || exit 1
fi
OPENCODE_PASSWORD=$(cat "$state/password") || exit 1
export OPENCODE_PASSWORD

if ! up; then
	(
		cd "$HOME" || exit 1
		nohup grun "$bin" serve --hostname 127.0.0.1 --port "$port" \\
			</dev/null >"$state/server.log" 2>&1 &
		echo $! >"$state/server.pid"
	)
	for _ in $(seq 1 150); do
		up && break
		sleep 0.1
	done
	if ! up; then
		echo "opencode: the server did not start; see $state/server.log" >&2
		exit 1
	fi
fi

# Command groups (mcp, debug, plugin) reject --server; their leaf commands
# take it anywhere, so it goes last, or before a `--` separator.
url="http://127.0.0.1:$port"
args=()
added=
for arg in "$@"; do
	if [ -z "$added" ] && [ "$arg" = -- ]; then
		args+=(--server "$url")
		added=1
	fi
	args+=("$arg")
done
[ -n "$added" ] || args+=(--server "$url")
exec grun "$bin" "${{args[@]}}"
"""


def stop_server(lay):
    """Stop the launcher's server so the next command starts the new binary.

    Only a pid whose command line still names our binary is signalled, so a
    stale pid file can never kill an unrelated process.
    """
    pid_file = os.path.join(lay.state, "server.pid")
    try:
        with open(pid_file) as f:
            pid = int(f.read().strip())
        with open(f"/proc/{pid}/cmdline", "rb") as f:
            cmdline = f.read()
    except (OSError, ValueError):
        return False
    if lay.binary.encode() not in cmdline:
        return False
    try:
        os.kill(pid, signal.SIGTERM)
    except OSError:
        return False
    return True


TOOL = Tool(
    name="opencode",
    label="OpenCode",
    package="@opencode/cli",
    os_words={"linux": "linux", "darwin": "darwin", "windows": "windows"},
    installer="install_opencode.py",
    launcher=launcher,
    baseline=True,
    after_install=stop_server,
)

if __name__ == "__main__":
    sys.exit(main(TOOL))
